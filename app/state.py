TRANSITIONS = {
 "IDEA_CREATED":{"SCRIPT_GENERATED","GENERATION_FAILED"},
 "SCRIPT_GENERATED":{"ASSETS_READY","GENERATION_FAILED"},
 "ASSETS_READY":{"RENDERING","RENDER_FAILED"},
 "RENDERING":{"RENDERED","RENDER_FAILED"},
 "RENDERED":{"QUALITY_CHECKING"},
 "QUALITY_CHECKING":{"AWAITING_APPROVAL","QUALITY_FAILED"},
 "AWAITING_APPROVAL":{"APPROVED","CANCELLED"},
 "APPROVED":{"SCHEDULED","PUBLISHING"},
 "SCHEDULED":{"PUBLISHING","CANCELLED"},
 "PUBLISHING":{"PROCESSING","PUBLISH_FAILED"},
 "PROCESSING":{"PUBLISHED","PUBLISH_FAILED"},
}
def move(reel, status):
    if status not in TRANSITIONS.get(reel.status, set()):
        raise ValueError(f"Invalid transition {reel.status} -> {status}")
    reel.status = status

